export const QUESTION_POOL: Record<Mode, string[]> = {
  mixed: [...mixed, ...common],
  male: [...male, ...common],
  female: [...female, ...common],
};

/** 모드별 질문 풀에서 겹치지 않게 count개를 무작위로 뽑는다. */
export function pickQuestions(mode: Mode, count: number, rand: () => number = Math.random): string[] {
  const pool = [...new Set(QUESTION_POOL[mode])];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}
